-- ---------------------------------------------------------------------
-- CADASTROS
-- ---------------------------------------------------------------------

create table fornecedor (
  id                  number generated by default on null as identity
                      constraint fornecedor_pk primary key,
  cnpj                varchar2(14)  not null,   -- só caracteres, sem máscara
  razao_social        varchar2(150) not null,
  nome_fantasia       varchar2(150),
  inscricao_estadual  varchar2(20),
  uf                  char(2),
  email               varchar2(200),
  prazo_padrao_dias   number(3),                -- prazo de pagamento usual
  ativo               char(1) default 'S' not null,
  criado_em           timestamp default systimestamp not null,
  criado_por          varchar2(100),
  atualizado_em       timestamp,
  atualizado_por      varchar2(100),
  constraint fornecedor_cnpj_uk unique (cnpj),
  -- desde jul/2026 o CNPJ pode ser alfanumérico (12 posições A-Z/0-9 + 2 DV numéricos)
  constraint fornecedor_cnpj_ck check (regexp_like(cnpj, '^[0-9A-Z]{12}[0-9]{2}$')),
  constraint fornecedor_ativo_ck check (ativo in ('S','N')),
  constraint fornecedor_uf_ck check (uf in (
    'AC','AL','AP','AM','BA','CE','DF','ES','GO','MA','MT','MS','MG','PA',
    'PB','PR','PE','PI','RJ','RN','RS','RO','RR','SC','SP','SE','TO'))
);

comment on table fornecedor is 'Emitentes das notas fiscais que a empresa precisa pagar.';

create table categoria_despesa (
  id            number generated by default on null as identity
                constraint categoria_despesa_pk primary key,
  nome          varchar2(80) not null,
  tipo          varchar2(20) not null,
  ativo         char(1) default 'S' not null,
  constraint categoria_despesa_nome_uk unique (nome),
  -- MERCADORIA = itens da nota entram no estoque
  constraint categoria_despesa_tipo_ck check (tipo in ('MERCADORIA','SERVICO','DESPESA_GERAL')),
  constraint categoria_despesa_ativo_ck check (ativo in ('S','N'))
);

comment on table categoria_despesa is 'Classifica a nota para análise de despesas e define se gera estoque.';

create table produto (
  id              number generated by default on null as identity
                  constraint produto_pk primary key,
  codigo          varchar2(30)  not null,       -- código interno da empresa
  descricao       varchar2(200) not null,
  unidade         varchar2(6)   default 'UN' not null,
  ncm             varchar2(8),
  estoque_minimo  number(15,3)  default 0 not null,
  ativo           char(1) default 'S' not null,
  criado_em       timestamp default systimestamp not null,
  constraint produto_codigo_uk unique (codigo),
  constraint produto_ncm_ck check (ncm is null or regexp_like(ncm, '^[0-9]{8}$')),
  constraint produto_minimo_ck check (estoque_minimo >= 0),
  constraint produto_ativo_ck check (ativo in ('S','N'))
);

comment on table produto is 'Produtos controlados no estoque interno.';

-- "De-para": cada fornecedor chama o mesmo produto por um código/descrição diferente.
-- É aqui que a leitura da IA vai ser casada com o produto interno.
create table produto_fornecedor (
  id                   number generated by default on null as identity
                       constraint produto_fornecedor_pk primary key,
  produto_id           number not null constraint produto_fornecedor_prod_fk references produto,
  fornecedor_id        number not null constraint produto_fornecedor_forn_fk references fornecedor,
  codigo_no_fornecedor varchar2(60) not null,
  descricao_no_fornecedor varchar2(200),
  fator_conversao      number(15,6) default 1 not null,  -- ex.: 1 CX do fornecedor = 12 UN
  constraint produto_fornecedor_uk unique (fornecedor_id, codigo_no_fornecedor),
  constraint produto_fornecedor_fator_ck check (fator_conversao > 0)
);

create index produto_fornecedor_prod_ix on produto_fornecedor (produto_id);

-- ---------------------------------------------------------------------
-- DOCUMENTO (foto enviada) - usado a partir da fase 2
-- ---------------------------------------------------------------------

create table nf_documento (
  id              number generated by default on null as identity
                  constraint nf_documento_pk primary key,
  nome_arquivo    varchar2(400) not null,
  mime_type       varchar2(100) not null,
  tamanho_bytes   number,
  imagem          blob not null,
  hash_sha256     varchar2(64),            -- evita processar a mesma foto duas vezes
  status          varchar2(20) default 'PENDENTE' not null,
  tentativas      number(2) default 0 not null,
  resposta_ia     json,                    -- JSON bruto devolvido pela IA
  modelo_ia       varchar2(100),
  tokens_entrada  number,
  tokens_saida    number,
  mensagem_erro   varchar2(4000),
  enviado_em      timestamp default systimestamp not null,
  enviado_por     varchar2(100),
  processado_em   timestamp,
  constraint nf_documento_hash_uk unique (hash_sha256),
  constraint nf_documento_status_ck check (status in ('PENDENTE','PROCESSANDO','EXTRAIDO','ERRO','DESCARTADO'))
);

comment on table nf_documento is 'Foto da nota enviada pelo usuário e resultado bruto da leitura por IA.';

-- ---------------------------------------------------------------------
-- NOTA FISCAL
-- ---------------------------------------------------------------------

create table nota_fiscal (
  id                 number generated by default on null as identity
                     constraint nota_fiscal_pk primary key,
  documento_id       number constraint nota_fiscal_doc_fk references nf_documento,
  fornecedor_id      number not null constraint nota_fiscal_forn_fk references fornecedor,
  categoria_id       number not null constraint nota_fiscal_cat_fk references categoria_despesa,
  chave_acesso       varchar2(44),
  modelo             varchar2(2)  default '55' not null,  -- 55 NF-e | 65 NFC-e
  serie              number(3)    not null,
  numero             number(9)    not null,
  data_emissao       date         not null,
  data_entrada       date,                               -- quando a mercadoria chegou
  natureza_operacao  varchar2(100),
  valor_produtos     number(15,2) default 0 not null,
  valor_desconto     number(15,2) default 0 not null,
  valor_frete        number(15,2) default 0 not null,
  valor_outras       number(15,2) default 0 not null,
  valor_total        number(15,2) not null,
  status             varchar2(20) default 'RASCUNHO' not null,
  origem             varchar2(10) default 'MANUAL' not null,
  observacao         varchar2(4000),
  aprovado_em        timestamp,
  aprovado_por       varchar2(100),
  criado_em          timestamp default systimestamp not null,
  criado_por         varchar2(100),
  atualizado_em      timestamp,
  atualizado_por     varchar2(100),
  constraint nota_fiscal_chave_uk  unique (chave_acesso),
  constraint nota_fiscal_numero_uk unique (fornecedor_id, modelo, serie, numero),
  constraint nota_fiscal_chave_ck  check (chave_acesso is null or regexp_like(chave_acesso, '^[0-9A-Z]{43}[0-9]$')),
  constraint nota_fiscal_modelo_ck check (modelo in ('55','65')),
  constraint nota_fiscal_status_ck check (status in ('RASCUNHO','EM_REVISAO','APROVADA','REJEITADA','CANCELADA')),
  constraint nota_fiscal_origem_ck check (origem in ('MANUAL','IA')),
  constraint nota_fiscal_valores_ck check (
    valor_produtos >= 0 and valor_desconto >= 0 and valor_frete >= 0
    and valor_outras >= 0 and valor_total >= 0)
);

create index nota_fiscal_forn_ix   on nota_fiscal (fornecedor_id);
create index nota_fiscal_cat_ix    on nota_fiscal (categoria_id);
create index nota_fiscal_doc_ix    on nota_fiscal (documento_id);
create index nota_fiscal_emissao_ix on nota_fiscal (data_emissao, status);

comment on table nota_fiscal is 'Cabeçalho da nota fiscal de entrada (a pagar).';

create table nf_item (
  id               number generated by default on null as identity
                   constraint nf_item_pk primary key,
  nota_id          number not null constraint nf_item_nota_fk references nota_fiscal on delete cascade,
  nr_item          number(3) not null,
  produto_id       number constraint nf_item_prod_fk references produto, -- preenchido no de-para
  codigo_produto   varchar2(60),       -- código como veio na nota (do fornecedor)
  descricao        varchar2(200) not null,
  ncm              varchar2(8),
  cfop             varchar2(4),
  unidade          varchar2(6),
  quantidade       number(15,4) not null,
  valor_unitario   number(15,4) not null,
  valor_total      number(15,2) not null,
  constraint nf_item_uk unique (nota_id, nr_item),
  constraint nf_item_qtd_ck check (quantidade > 0),
  constraint nf_item_valor_ck check (valor_unitario >= 0 and valor_total >= 0)
);

create index nf_item_prod_ix on nf_item (produto_id);

-- Duplicatas = parcelas a pagar. É daqui que sai o contas a pagar.
create table nf_duplicata (
  id               number generated by default on null as identity
                   constraint nf_duplicata_pk primary key,
  nota_id          number not null constraint nf_duplicata_nota_fk references nota_fiscal on delete cascade,
  numero_parcela   number(3) not null,
  data_vencimento  date not null,
  valor            number(15,2) not null,
  status           varchar2(15) default 'ABERTA' not null,
  data_pagamento   date,
  valor_pago       number(15,2),
  forma_pagamento  varchar2(20),
  criado_em        timestamp default systimestamp not null,
  criado_por       varchar2(100),
  atualizado_em    timestamp,
  atualizado_por   varchar2(100),
  constraint nf_duplicata_uk unique (nota_id, numero_parcela),
  constraint nf_duplicata_valor_ck check (valor > 0),
  constraint nf_duplicata_status_ck check (status in ('ABERTA','PAGA','CANCELADA')),
  constraint nf_duplicata_pago_ck check (
    (status = 'PAGA' and data_pagamento is not null and valor_pago is not null)
    or status <> 'PAGA'),
  constraint nf_duplicata_forma_ck check (forma_pagamento is null or
    forma_pagamento in ('BOLETO','PIX','TRANSFERENCIA','CARTAO','DINHEIRO'))
);

create index nf_duplicata_venc_ix on nf_duplicata (status, data_vencimento);

create table nf_imposto (
  id             number generated by default on null as identity
                 constraint nf_imposto_pk primary key,
  nota_id        number not null constraint nf_imposto_nota_fk references nota_fiscal on delete cascade,
  tipo           varchar2(10) not null,
  base_calculo   number(15,2) default 0 not null,
  aliquota       number(7,4),
  valor          number(15,2) default 0 not null,
  constraint nf_imposto_uk unique (nota_id, tipo),
  -- IPI e ICMS_ST somam no total da nota; os demais são informativos
  constraint nf_imposto_tipo_ck check (tipo in ('ICMS','ICMS_ST','IPI','PIS','COFINS','ISS'))
);

-- Resultado da validação: alimenta a tela de revisão no APEX
create table nf_inconsistencia (
  id           number generated by default on null as identity
               constraint nf_inconsistencia_pk primary key,
  nota_id      number not null constraint nf_inconsistencia_nota_fk references nota_fiscal on delete cascade,
  regra        varchar2(40) not null,
  severidade   varchar2(10) not null,
  mensagem     varchar2(1000) not null,
  criado_em    timestamp default systimestamp not null,
  constraint nf_inconsistencia_sev_ck check (severidade in ('ERRO','ALERTA'))
);

create index nf_inconsistencia_nota_ix on nf_inconsistencia (nota_id);

-- ---------------------------------------------------------------------
-- ESTOQUE
-- ---------------------------------------------------------------------

-- O saldo nunca é digitado: ele é a soma dos movimentos (rastreável e auditável).
create table estoque_movimento (
  id               number generated by default on null as identity
                   constraint estoque_movimento_pk primary key,
  produto_id       number not null constraint estoque_mov_prod_fk references produto,
  tipo             varchar2(10) not null,
  quantidade       number(15,3) not null,     -- sempre positiva; o tipo define o sinal
  custo_unitario   number(15,4),
  data_movimento   date default trunc(sysdate) not null,
  nf_item_id       number constraint estoque_mov_item_fk references nf_item,
  movimento_origem_id number constraint estoque_mov_estorno_fk references estoque_movimento,
  observacao       varchar2(400),
  criado_em        timestamp default systimestamp not null,
  criado_por       varchar2(100),
  constraint estoque_mov_tipo_ck check (tipo in ('ENTRADA','SAIDA','AJUSTE_MAIS','AJUSTE_MENOS','ESTORNO')),
  constraint estoque_mov_qtd_ck check (quantidade > 0)
);

create index estoque_mov_prod_ix on estoque_movimento (produto_id, data_movimento);
create index estoque_mov_item_ix on estoque_movimento (nf_item_id);

comment on table estoque_movimento is 'Kardex: toda entrada/saída de estoque. Entradas de nota vêm de pkg_nf_processo.aprovar_nota.';

-- ---------------------------------------------------------------------
-- LOG TÉCNICO (chamadas à IA, jobs, erros)
-- ---------------------------------------------------------------------

create table nf_log (
  id            number generated by default on null as identity
                constraint nf_log_pk primary key,
  documento_id  number constraint nf_log_doc_fk references nf_documento on delete cascade,
  nota_id       number constraint nf_log_nota_fk references nota_fiscal on delete cascade,
  etapa         varchar2(40) not null,
  nivel         varchar2(10) default 'INFO' not null,
  mensagem      varchar2(4000) not null,
  detalhe       clob,
  criado_em     timestamp default systimestamp not null,
  constraint nf_log_nivel_ck check (nivel in ('INFO','AVISO','ERRO'))
);

create index nf_log_doc_ix  on nf_log (documento_id);
create index nf_log_nota_ix on nf_log (nota_id);
